#!/usr/bin/env node

// 🧪 SYSTÈME VALIDATION CHECKPOINT GEMINI

const fs = require('fs');
const path = require('path');

class ValidationCheckpointSystem {
    constructor() {
        this.workLogFile = '.session-work.log';
        this.validationFile = '.gemini_validated';
        this.context7File = '.context7_validated';
        this.checkpointThreshold = 5; // Validation requise tous les 5 changements
    }

    // 📊 Status des validations actuelles
    getValidationStatus() {
        const workCount = this.getWorkCount();
        const hasContext7 = fs.existsSync(this.context7File);
        const hasGeminiValidation = fs.existsSync(this.validationFile);
        
        return {
            workCount,
            hasContext7,
            hasGeminiValidation,
            needsValidation: workCount >= this.checkpointThreshold && !hasGeminiValidation,
            nextCheckpoint: this.checkpointThreshold - workCount,
            status: this.determineStatus(workCount, hasContext7, hasGeminiValidation)
        };
    }

    // 📈 Compter le travail effectué
    getWorkCount() {
        if (!fs.existsSync(this.workLogFile)) return 0;
        
        const content = fs.readFileSync(this.workLogFile, 'utf8');
        return content.split('\n').filter(line => line.trim()).length;
    }

    // 🎯 Déterminer status global
    determineStatus(workCount, hasContext7, hasGeminiValidation) {
        if (!hasContext7) return 'BLOCKED_CONTEXT7';
        if (workCount === 0) return 'READY_TO_WORK';
        if (workCount < this.checkpointThreshold) return 'WORKING';
        if (!hasGeminiValidation) return 'BLOCKED_VALIDATION';
        return 'VALIDATED_READY';
    }

    // 📋 Générer prompt de validation pour Gemini
    generateGeminiValidationPrompt() {
        const status = this.getValidationStatus();
        
        const prompt = `# 🧪 GEMINI VALIDATION CHECKPOINT

## 📊 Session Status
- Code changes made: ${status.workCount}
- Context7 validated: ${status.hasContext7 ? '✅' : '❌'}
- Previous validation: ${status.hasGeminiValidation ? '✅' : '❌'}

## 🔍 Validation Request
Please review the recent code changes and provide feedback on:

### 1. 🎨 INNOVATION & CREATIVITY (Score 0-100)
- Are there more innovative approaches?
- Could we use more modern technologies?
- Any creative optimizations missed?

### 2. ⚡ PERFORMANCE & EFFICIENCY (Score 0-100) 
- Is the code performant?
- Are there bottlenecks or inefficiencies?
- Memory/CPU usage optimizations?

### 3. 🛡️ SECURITY & BEST PRACTICES (Score 0-100)
- Any security vulnerabilities?
- Following industry best practices?
- Code quality and maintainability?

### 4. 🚀 SCALABILITY & FUTURE-PROOFING (Score 0-100)
- Will this scale with growth?
- Easy to maintain and extend?
- Architecture decisions sound?

## 📋 Required Response Format
\`\`\`json
{
  "validation_id": "checkpoint_${Date.now()}",
  "scores": {
    "innovation": 0-100,
    "performance": 0-100, 
    "security": 0-100,
    "scalability": 0-100
  },
  "overall_score": 0-100,
  "status": "APPROVED|NEEDS_CHANGES",
  "feedback": [
    "Specific feedback item 1",
    "Specific feedback item 2"
  ],
  "next_steps": [
    "Action item 1",
    "Action item 2"
  ]
}
\`\`\`

## ✅ Approval Criteria
- Overall score >= 85: APPROVED (continue development)
- Overall score < 85: NEEDS_CHANGES (address feedback first)

---
*Generated by Archon Orchestrator Validation System*
`;

        return prompt;
    }

    // 💾 Sauvegarder réponse validation Gemini
    saveGeminiValidation(validationResponse) {
        const validation = {
            timestamp: new Date().toISOString(),
            workCount: this.getWorkCount(),
            response: validationResponse,
            checkpoint: `checkpoint_${Date.now()}`
        };

        // Sauvegarder validation
        fs.writeFileSync(
            '.gemini_validation_history.json',
            JSON.stringify(validation, null, 2)
        );

        // Marquer comme validé si approuvé
        if (validationResponse.status === 'APPROVED') {
            fs.writeFileSync(this.validationFile, validation.timestamp);
            // Reset work counter après validation
            if (fs.existsSync(this.workLogFile)) {
                fs.unlinkSync(this.workLogFile);
            }
            return { success: true, message: 'Validation approved - work counter reset' };
        }

        return { success: false, message: 'Validation requires changes - address feedback first' };
    }

    // 🔄 Reset validation state
    resetValidationState() {
        const filesToRemove = [
            this.workLogFile,
            this.validationFile,
            this.context7File,
            '.gemini_validation_history.json'
        ];

        filesToRemove.forEach(file => {
            if (fs.existsSync(file)) {
                fs.unlinkSync(file);
            }
        });

        console.log('✅ Validation state reset - ready for new session');
    }

    // 📊 Générer rapport de validation
    generateValidationReport() {
        const status = this.getValidationStatus();
        
        const report = {
            timestamp: new Date().toISOString(),
            status: status.status,
            details: {
                workCount: status.workCount,
                hasContext7: status.hasContext7,
                hasGeminiValidation: status.hasGeminiValidation,
                needsValidation: status.needsValidation,
                nextCheckpoint: status.nextCheckpoint
            },
            actions: this.getRequiredActions(status),
            prompt: status.needsValidation ? this.generateGeminiValidationPrompt() : null
        };

        console.log('\n📊 VALIDATION CHECKPOINT REPORT:');
        console.log(`Status: ${report.status}`);
        console.log(`Work count: ${report.details.workCount}`);
        console.log(`Context7: ${report.details.hasContext7 ? '✅' : '❌'}`);
        console.log(`Gemini validation: ${report.details.hasGeminiValidation ? '✅' : '❌'}`);
        
        if (report.actions.length > 0) {
            console.log('\n📋 REQUIRED ACTIONS:');
            report.actions.forEach((action, i) => {
                console.log(`${i + 1}. ${action}`);
            });
        }

        return report;
    }

    // 🎯 Actions requises selon le status
    getRequiredActions(status) {
        const actions = [];
        
        if (!status.hasContext7) {
            actions.push('Run Context7 validation: /mcp context7 resolve-library-id <library>');
            actions.push('Get library docs: /mcp context7 get-library-docs <id>');
        }
        
        if (status.needsValidation) {
            actions.push('Send code to Gemini for validation');
            actions.push('Wait for Gemini approval before continuing');
            actions.push('Address any feedback from Gemini');
        }
        
        if (status.workCount > 0 && status.nextCheckpoint <= 1) {
            actions.push(`Next validation checkpoint in ${status.nextCheckpoint} changes`);
        }

        return actions;
    }
}

// CLI interface
if (require.main === module) {
    const system = new ValidationCheckpointSystem();
    const command = process.argv[2];

    switch (command) {
        case 'status':
            system.generateValidationReport();
            break;
            
        case 'prompt':
            const prompt = system.generateGeminiValidationPrompt();
            console.log(prompt);
            break;
            
        case 'reset':
            system.resetValidationState();
            break;
            
        case 'approve':
            // Simulation d'approbation Gemini
            const mockResponse = {
                validation_id: `checkpoint_${Date.now()}`,
                scores: { innovation: 90, performance: 85, security: 88, scalability: 87 },
                overall_score: 87.5,
                status: 'APPROVED',
                feedback: ['Good architecture choices', 'Performance optimizations look solid'],
                next_steps: ['Continue with implementation', 'Monitor performance in production']
            };
            const result = system.saveGeminiValidation(mockResponse);
            console.log(result.message);
            break;
            
        default:
            console.log('Usage: node validation-checkpoint-system.cjs [status|prompt|reset|approve]');
            console.log('  status  - Show current validation status');
            console.log('  prompt  - Generate Gemini validation prompt');
            console.log('  reset   - Reset all validation state');
            console.log('  approve - Simulate Gemini approval (testing)');
    }
}

module.exports = { ValidationCheckpointSystem };